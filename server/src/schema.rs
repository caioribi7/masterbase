//! Tela Estrutura: criar e mudar tabelas e colunas sem SQL.
//! Nomes novos passam por valid_name + ident; nomes existentes são conferidos no catálogo; tipos vêm de uma lista fixa.
use crate::activity::log;
use crate::auth::User;
use crate::catalog::{columns, ident, kind_sql, valid_name, Col};
use crate::error::{bad, ApiResult};
use axum::extract::{Path, State};
use axum::Json;
use serde::Deserialize;
use serde_json::{json, Value};
use sqlx::PgPool;

pub async fn get_schema(_user: User, State(db): State<PgPool>) -> ApiResult<Json<Value>> {
    let cols = columns(&db, None).await?;
    let mut tables: Vec<Value> = Vec::new();
    let mut current = "";
    for c in &cols {
        if c.table != current {
            current = &c.table;
            tables.push(json!({ "name": c.table, "columns": [] }));
        }
        if let Some(Value::Array(list)) = tables.last_mut().and_then(|t| t.get_mut("columns")) {
            list.push(c.json());
        }
    }
    Ok(Json(Value::Array(tables)))
}

#[derive(Deserialize)]
pub struct NewCol {
    name: String,
    kind: String,
    #[serde(default)]
    required: bool,
    #[serde(default)]
    unique: bool,
    link: Option<String>,
}

/// Pedaço "nome tipo [REFERENCES ...] [NOT NULL] [UNIQUE]" de uma coluna nova.
async fn col_sql(db: &PgPool, c: &NewCol) -> ApiResult<(String, String)> {
    let name = valid_name(&c.name)?;
    let ty = if c.kind == "ligação" {
        let target = c.link.as_deref().ok_or(bad("Escolha a tabela da ligação."))?;
        let cols = columns(db, Some(target)).await?;
        let pk = cols.iter().find(|x| x.pk).ok_or(bad("A tabela ligada precisa ter chave primária."))?;
        // pk.ty sai de format_type() do catálogo.
        format!("{} REFERENCES public.{}({})", pk.ty, ident(target), ident(&pk.name))
    } else {
        kind_sql(&c.kind).ok_or(bad("Tipo de coluna desconhecido."))?.to_owned()
    };
    let mut sql = format!("{} {ty}", ident(&name));
    if c.required {
        sql += " NOT NULL";
    }
    if c.unique {
        sql += " UNIQUE";
    }
    Ok((name, sql))
}

async fn ddl(db: &PgPool, sql: &str) -> ApiResult<()> {
    sqlx::query(sql).persistent(false).execute(db).await?;
    Ok(())
}

#[derive(Deserialize)]
pub struct NewTable {
    name: String,
    columns: Vec<NewCol>,
}

pub async fn create_table(user: User, State(db): State<PgPool>, Json(b): Json<NewTable>) -> ApiResult<Json<Value>> {
    user.admin()?;
    let name = valid_name(&b.name)?;
    if b.columns.len() > 100 {
        return Err(bad("Máximo de 100 colunas."));
    }
    // Toda tabela nasce com chave "id" automática: é ela que permite editar e apagar linhas.
    let mut parts = vec!["id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY".to_owned()];
    for c in &b.columns {
        parts.push(col_sql(&db, c).await?.1);
    }
    ddl(&db, &format!("CREATE TABLE public.{} ({})", ident(&name), parts.join(", "))).await?;
    log(&db, user.id, "create_table", json!({ "table": name })).await?;
    Ok(Json(json!({ "name": name })))
}

#[derive(Deserialize)]
pub struct Rename {
    name: String,
}

pub async fn rename_table(user: User, State(db): State<PgPool>, Path(table): Path<String>, Json(b): Json<Rename>) -> ApiResult<Json<Value>> {
    user.admin()?;
    columns(&db, Some(&table)).await?;
    let to = valid_name(&b.name)?;
    ddl(&db, &format!("ALTER TABLE public.{} RENAME TO {}", ident(&table), ident(&to))).await?;
    log(&db, user.id, "rename_table", json!({ "table": table, "to": to })).await?;
    Ok(Json(json!({ "name": to })))
}

#[derive(Deserialize)]
pub struct Confirm {
    confirm: String,
}

pub async fn drop_table(user: User, State(db): State<PgPool>, Path(table): Path<String>, Json(b): Json<Confirm>) -> ApiResult<Json<Value>> {
    user.admin()?;
    columns(&db, Some(&table)).await?;
    if b.confirm != table {
        return Err(bad("Digite o nome da tabela para confirmar."));
    }
    // Sem CASCADE: se outra tabela liga nesta, o Postgres recusa e o usuário vê o motivo.
    ddl(&db, &format!("DROP TABLE public.{}", ident(&table))).await?;
    log(&db, user.id, "drop_table", json!({ "table": table })).await?;
    Ok(Json(json!({ "ok": true })))
}

pub async fn add_column(user: User, State(db): State<PgPool>, Path(table): Path<String>, Json(c): Json<NewCol>) -> ApiResult<Json<Value>> {
    user.admin()?;
    columns(&db, Some(&table)).await?;
    let (name, sql) = col_sql(&db, &c).await?;
    ddl(&db, &format!("ALTER TABLE public.{} ADD COLUMN {sql}", ident(&table))).await?;
    log(&db, user.id, "add_column", json!({ "table": table, "column": name })).await?;
    Ok(Json(json!({ "name": name })))
}

fn editable<'a>(cols: &'a [Col], name: &str) -> ApiResult<&'a Col> {
    let col = cols.iter().find(|c| c.name == name).ok_or(bad("Coluna não existe."))?;
    if col.pk {
        return Err(bad("A chave da tabela não pode ser mudada."));
    }
    Ok(col)
}

#[derive(Deserialize)]
pub struct ColChange {
    name: Option<String>,
    required: Option<bool>,
}

pub async fn change_column(
    user: User,
    State(db): State<PgPool>,
    Path((table, column)): Path<(String, String)>,
    Json(b): Json<ColChange>,
) -> ApiResult<Json<Value>> {
    user.admin()?;
    let cols = columns(&db, Some(&table)).await?;
    let col = editable(&cols, &column)?;
    let t = ident(&table);
    let mut tx = db.begin().await?;
    if let Some(req) = b.required.filter(|r| *r != col.required) {
        let verb = if req { "SET" } else { "DROP" };
        sqlx::query(&format!("ALTER TABLE public.{t} ALTER COLUMN {} {verb} NOT NULL", ident(&col.name)))
            .persistent(false)
            .execute(&mut *tx)
            .await?;
    }
    let mut final_name = col.name.clone();
    if let Some(n) = &b.name {
        let n = valid_name(n)?;
        if n != col.name {
            sqlx::query(&format!("ALTER TABLE public.{t} RENAME COLUMN {} TO {}", ident(&col.name), ident(&n)))
                .persistent(false)
                .execute(&mut *tx)
                .await?;
            final_name = n;
        }
    }
    tx.commit().await?;
    log(&db, user.id, "change_column", json!({ "table": table, "column": col.name, "renamed": final_name, "required": b.required })).await?;
    Ok(Json(json!({ "name": final_name })))
}

pub async fn drop_column(user: User, State(db): State<PgPool>, Path((table, column)): Path<(String, String)>) -> ApiResult<Json<Value>> {
    user.admin()?;
    let cols = columns(&db, Some(&table)).await?;
    let col = editable(&cols, &column)?;
    ddl(&db, &format!("ALTER TABLE public.{} DROP COLUMN {}", ident(&table), ident(&col.name))).await?;
    log(&db, user.id, "drop_column", json!({ "table": table, "column": col.name })).await?;
    Ok(Json(json!({ "ok": true })))
}
