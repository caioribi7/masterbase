//! Tela Estrutura: criar e mudar tabelas e colunas sem SQL.
//! Nomes novos passam por valid_name + ident; nomes existentes são conferidos no catálogo; tipos vêm de uma lista fixa.
use crate::auth::User;
use crate::projects::Db;
use crate::catalog::{columns, ident, kind_sql, valid_name, Col};
use crate::error::{bad, ApiError, ApiResult};
use axum::extract::Path;
use axum::Json;
use serde::Deserialize;
use serde_json::{json, Value};
use sqlx::PgPool;

pub async fn get_schema(_user: User, p: Db) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    let cols = columns(&db, None).await?;
    let rules = crate::rules::list(&p).await?;
    let mut tables: Vec<Value> = Vec::new();
    let mut current = "";
    for c in &cols {
        if c.table != current {
            current = &c.table;
            // owner: coluna com o e-mail do dono da linha (regra por linha), ou null.
            tables.push(json!({ "name": c.table, "columns": [], "owner": rules.get(&c.table) }));
        }
        if let Some(Value::Array(list)) = tables.last_mut().and_then(|t| t.get_mut("columns")) {
            list.push(c.json());
        }
    }
    Ok(Json(Value::Array(tables)))
}

#[derive(Deserialize)]
pub struct NewCol {
    name: String,
    kind: String,
    #[serde(default)]
    required: bool,
    #[serde(default)]
    unique: bool,
    link: Option<String>,
    default: Option<DefaultSpec>,
}

/// Valor padrão escolhido na tela. mode: nenhum | fixo | agora | hoje | id novo.
#[derive(Deserialize)]
pub struct DefaultSpec {
    mode: String,
    #[serde(default)]
    value: String,
}

/// Expressão SQL do padrão para uma coluna do tipo `ty` (vindo do catálogo ou de kind_sql). None = sem padrão.
/// Texto fixo vira literal com aspas dobradas e cast para o tipo: o Postgres confere o valor na hora.
fn default_sql(d: &DefaultSpec, ty: &str) -> ApiResult<Option<String>> {
    let time = ty.starts_with("timestamp") || ty == "timestamptz" || ty == "date";
    Ok(Some(match d.mode.as_str() {
        "nenhum" => return Ok(None),
        "agora" if time => "now()".into(),
        "hoje" if time => "CURRENT_DATE".into(),
        "id novo" if ty == "uuid" => "gen_random_uuid()".into(),
        "agora" | "hoje" => return Err(bad("Agora e hoje só valem para colunas de data.")),
        "id novo" => return Err(bad("Id novo só vale para colunas de id único.")),
        "fixo" => {
            if d.value.chars().count() > 1000 {
                return Err(bad("Valor padrão grande demais (até 1000 caracteres)."));
            }
            format!("'{}'::{ty}", d.value.replace('\'', "''"))
        }
        _ => return Err(bad("Tipo de valor padrão desconhecido.")),
    }))
}

/// Erro de conversão de valor vira frase. O resto segue o mapa geral.
fn cast_error(e: sqlx::Error) -> ApiError {
    let code = e.as_database_error().and_then(|d| d.code()).map(|c| c.into_owned());
    match code.as_deref() {
        Some(c) if c.starts_with("22") || c == "42804" || c == "42846" => {
            bad("Alguns valores não combinam com o tipo escolhido. Ajuste esses valores e tente de novo.")
        }
        _ => e.into(),
    }
}

/// Pedaço "nome tipo [REFERENCES ...] [NOT NULL] [UNIQUE]" de uma coluna nova.
async fn col_sql(db: &PgPool, c: &NewCol) -> ApiResult<(String, String)> {
    let name = valid_name(&c.name)?;
    let ty = if c.kind == "ligação" {
        let target = c.link.as_deref().ok_or(bad("Escolha a tabela da ligação."))?;
        let cols = columns(db, Some(target)).await?;
        let pk = cols.iter().find(|x| x.pk).ok_or(bad("A tabela ligada precisa ter chave primária."))?;
        // pk.ty sai de format_type() do catálogo.
        format!("{} REFERENCES public.{}({})", pk.ty, ident(target), ident(&pk.name))
    } else {
        kind_sql(&c.kind).ok_or(bad("Tipo de coluna desconhecido."))?.to_owned()
    };
    let mut sql = format!("{} {ty}", ident(&name));
    if let Some(d) = &c.default {
        if c.kind == "ligação" && d.mode != "nenhum" {
            return Err(bad("Ligação não tem valor padrão."));
        }
        if let Some(expr) = default_sql(d, &ty)? {
            sql += &format!(" DEFAULT {expr}");
        }
    }
    if c.required {
        sql += " NOT NULL";
    }
    if c.unique {
        sql += " UNIQUE";
    }
    Ok((name, sql))
}

async fn ddl(db: &PgPool, sql: &str) -> ApiResult<()> {
    sqlx::query(sql).persistent(false).execute(db).await?;
    Ok(())
}

#[derive(Deserialize)]
pub struct NewTable {
    name: String,
    columns: Vec<NewCol>,
}

pub async fn create_table(user: User, p: Db, Json(b): Json<NewTable>) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    let name = valid_name(&b.name)?;
    if b.columns.len() > 100 {
        return Err(bad("Máximo de 100 colunas."));
    }
    // Toda tabela nasce com chave "id" automática: é ela que permite editar e apagar linhas.
    let mut parts = vec!["id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY".to_owned()];
    for c in &b.columns {
        parts.push(col_sql(&db, c).await?.1);
    }
    ddl(&db, &format!("CREATE TABLE public.{} ({})", ident(&name), parts.join(", "))).await?;
    p.log(user.id, "create_table", json!({ "table": name })).await?;
    Ok(Json(json!({ "name": name })))
}

#[derive(Deserialize)]
pub struct Rename {
    name: String,
}

pub async fn rename_table(user: User, p: Db, Path(table): Path<String>, Json(b): Json<Rename>) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    columns(&db, Some(&table)).await?;
    let to = valid_name(&b.name)?;
    ddl(&db, &format!("ALTER TABLE public.{} RENAME TO {}", ident(&table), ident(&to))).await?;
    sqlx::query("UPDATE masterbase.row_rules SET table_name = $2 WHERE project = $3 AND table_name = $1")
        .bind(&table)
        .bind(&to)
        .bind(p.project)
        .execute(&p.meta)
        .await?;
    p.log(user.id, "rename_table", json!({ "table": table, "to": to })).await?;
    Ok(Json(json!({ "name": to })))
}

#[derive(Deserialize)]
pub struct Confirm {
    confirm: String,
}

pub async fn drop_table(user: User, p: Db, Path(table): Path<String>, Json(b): Json<Confirm>) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    columns(&db, Some(&table)).await?;
    if b.confirm != table {
        return Err(bad("Digite o nome da tabela para confirmar."));
    }
    // Sem CASCADE: se outra tabela liga nesta, o Postgres recusa e o usuário vê o motivo.
    ddl(&db, &format!("DROP TABLE public.{}", ident(&table))).await?;
    sqlx::query("DELETE FROM masterbase.row_rules WHERE project = $2 AND table_name = $1").bind(&table).bind(p.project).execute(&p.meta).await?;
    p.log(user.id, "drop_table", json!({ "table": table })).await?;
    Ok(Json(json!({ "ok": true })))
}

pub async fn add_column(user: User, p: Db, Path(table): Path<String>, Json(c): Json<NewCol>) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    columns(&db, Some(&table)).await?;
    let (name, sql) = col_sql(&db, &c).await?;
    sqlx::query(&format!("ALTER TABLE public.{} ADD COLUMN {sql}", ident(&table)))
        .persistent(false)
        .execute(&db)
        .await
        .map_err(cast_error)?;
    p.log(user.id, "add_column", json!({ "table": table, "column": name })).await?;
    Ok(Json(json!({ "name": name })))
}

fn editable<'a>(cols: &'a [Col], name: &str) -> ApiResult<&'a Col> {
    let col = cols.iter().find(|c| c.name == name).ok_or(bad("Coluna não existe."))?;
    if col.pk {
        return Err(bad("A chave da tabela não pode ser mudada."));
    }
    Ok(col)
}

#[derive(Deserialize)]
pub struct ColChange {
    name: Option<String>,
    required: Option<bool>,
    /// Tipo novo, na lista da tela (texto, número, ...).
    kind: Option<String>,
    default: Option<DefaultSpec>,
}

pub async fn change_column(
    user: User,
    p: Db,
    Path((table, column)): Path<(String, String)>,
    Json(b): Json<ColChange>,
) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    let cols = columns(&db, Some(&table)).await?;
    let col = editable(&cols, &column)?;
    let t = ident(&table);
    let c = ident(&col.name);
    let mut tx = db.begin().await?;
    // Tipo primeiro: o padrão antigo pode não servir no tipo novo, então sai e volta se foi pedido.
    let mut ty = col.ty.clone();
    let mut changed_type = false;
    if let Some(kind) = &b.kind {
        let new_ty = kind_sql(kind).ok_or(bad("Tipo de coluna desconhecido."))?;
        let same = crate::catalog::label(&col.ty, &col.typtype) == kind.as_str();
        if !same {
            if col.link.is_some() {
                return Err(bad("Coluna de ligação não muda de tipo. Apague e crie outra."));
            }
            if col.default.as_deref() == Some("auto") {
                return Err(bad("Esta coluna numera sozinha e não muda de tipo."));
            }
            sqlx::query(&format!("ALTER TABLE public.{t} ALTER COLUMN {c} DROP DEFAULT"))
                .persistent(false)
                .execute(&mut *tx)
                .await?;
            // Passa por texto: funciona de qualquer tipo para qualquer tipo, e falha só se algum valor não converter.
            sqlx::query(&format!("ALTER TABLE public.{t} ALTER COLUMN {c} TYPE {new_ty} USING {c}::text::{new_ty}"))
                .persistent(false)
                .execute(&mut *tx)
                .await
                .map_err(cast_error)?;
            ty = new_ty.to_owned();
            changed_type = true;
        }
    }
    if let Some(d) = &b.default {
        if col.link.is_some() && d.mode != "nenhum" {
            return Err(bad("Ligação não tem valor padrão."));
        }
        if col.default.as_deref() == Some("auto") {
            return Err(bad("Esta coluna numera sozinha e não tem outro padrão."));
        }
        let sql = match default_sql(d, &ty)? {
            Some(expr) => format!("ALTER TABLE public.{t} ALTER COLUMN {c} SET DEFAULT {expr}"),
            None => format!("ALTER TABLE public.{t} ALTER COLUMN {c} DROP DEFAULT"),
        };
        sqlx::query(&sql).persistent(false).execute(&mut *tx).await.map_err(cast_error)?;
    }
    if let Some(req) = b.required.filter(|r| *r != col.required) {
        let verb = if req { "SET" } else { "DROP" };
        sqlx::query(&format!("ALTER TABLE public.{t} ALTER COLUMN {} {verb} NOT NULL", ident(&col.name)))
            .persistent(false)
            .execute(&mut *tx)
            .await?;
    }
    let mut final_name = col.name.clone();
    if let Some(n) = &b.name {
        let n = valid_name(n)?;
        if n != col.name {
            sqlx::query(&format!("ALTER TABLE public.{t} RENAME COLUMN {} TO {}", ident(&col.name), ident(&n)))
                .persistent(false)
                .execute(&mut *tx)
                .await?;
            final_name = n;
        }
    }
    tx.commit().await?;
    if final_name != col.name {
        sqlx::query("UPDATE masterbase.row_rules SET column_name = $3 WHERE project = $4 AND table_name = $1 AND column_name = $2")
            .bind(&table)
            .bind(&col.name)
            .bind(&final_name)
            .bind(p.project)
            .execute(&p.meta)
            .await?;
    }
    let detail = json!({
        "table": table, "column": col.name, "renamed": final_name, "required": b.required,
        "type": changed_type.then_some(&b.kind), "default": b.default.as_ref().map(|d| &d.mode),
    });
    p.log(user.id, "change_column", detail).await?;
    Ok(Json(json!({ "name": final_name })))
}

pub async fn drop_column(user: User, p: Db, Path((table, column)): Path<(String, String)>) -> ApiResult<Json<Value>> {
    let db = p.data.clone();
    user.admin()?;
    let cols = columns(&db, Some(&table)).await?;
    let col = editable(&cols, &column)?;
    if crate::rules::list(&p).await?.get(&table) == Some(&col.name) {
        return Err(bad("Esta coluna diz de quem é cada linha. Desligue a regra das linhas antes de apagar."));
    }
    ddl(&db, &format!("ALTER TABLE public.{} DROP COLUMN {}", ident(&table), ident(&col.name))).await?;
    p.log(user.id, "drop_column", json!({ "table": table, "column": col.name })).await?;
    Ok(Json(json!({ "ok": true })))
}
